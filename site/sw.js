const PREFIX = 'pathpatrol-';
const CACHE = `${PREFIX}${VERSION}-${SHELL_HASH}`;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // 'reload' skips the HTTP cache, so a file that was cached for ten minutes cannot be filed under the new version. Any
    // failure rejects, the install fails, and the version already running carries on untouched.
    await Promise.all(SHELL.map(async (path) => {
      const response = await fetch(path, { cache: 'reload' });
      if (!response.ok) throw new Error(`${path}: ${response.status}`);
      await cache.put(path, response);
    }));
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

/* The page asks for the takeover (Update ready, or a launch that reaches the title). */
self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request, { ignoreSearch: true });          // ?debug=1 and the like still get the app
    return hit || fetch(request);                                             // not part of the shell (the share image, robots.txt, some other path): the network
  })());
});
