/* Offline shell for Path Patrol.

   Every file the game needs is fetched once, whole, into a cache named for this version and its contents, and served from
   there first, page loads included. A page and its modules therefore always come from the same version: a new index.html
   next to old cached modules could break the import graph. A new version installs completely and then WAITS; the page
   decides when it takes over (js/pwa.js), so an update never arrives in the middle of a route.

   Browsers notice an update only when this file changes, so it changes whenever any shell file does: the block between the
   markers is written by tools/make_sw.py (run it after editing anything under site/; a test fails if it was forgotten).
   VERSION must equal APP_VERSION in js/config.js (a test checks that too). */
